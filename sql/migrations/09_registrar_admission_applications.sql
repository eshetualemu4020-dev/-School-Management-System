CREATE TABLE IF NOT EXISTS admission_applications (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  application_ref VARCHAR(32) NOT NULL,
  first_name VARCHAR(60) NOT NULL,
  father_name VARCHAR(60) NOT NULL,
  grandfather_name VARCHAR(60) NULL,
  gender ENUM('female', 'male') NOT NULL,
  date_of_birth DATE NOT NULL,
  phone VARCHAR(30) NULL,
  email VARCHAR(190) NULL,
  address VARCHAR(255) NULL,
  guardian_name VARCHAR(190) NULL,
  guardian_phone VARCHAR(30) NULL,
  previous_school VARCHAR(190) NULL,
  status ENUM('pending_review', 'approved', 'rejected', 'registered', 'withdrawn') NOT NULL DEFAULT 'pending_review',
  created_by BIGINT UNSIGNED NOT NULL,
  decided_by BIGINT UNSIGNED NULL,
  decision_note VARCHAR(500) NULL,
  decided_at DATETIME(3) NULL,
  registered_student_id BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_admission_applications_ref (application_ref),
  UNIQUE KEY uq_admission_applications_student (registered_student_id),
  KEY ix_admission_applications_status_created (status, created_at),
  KEY ix_admission_applications_name (father_name, first_name),
  CONSTRAINT fk_admission_applications_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_admission_applications_decided_by FOREIGN KEY (decided_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_admission_applications_student FOREIGN KEY (registered_student_id) REFERENCES students(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
